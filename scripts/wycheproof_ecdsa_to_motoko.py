#!/usr/bin/env python3
"""Converts a Wycheproof ECDSA verification file (schema
ecdsa_verify_schema_v1.json) into a Motoko module with one record per test,
in the format of test/ecdsa/wycheproofEcdsaSecp256k1TestVectors.mo.

Usage:
  python3 scripts/wycheproof_ecdsa_to_motoko.py ecdsa_secp256r1_sha256_test.json \
    > test/ecdsa/wycheproofEcdsaSecp256r1TestVectors.mo

Source: https://github.com/C2SP/wycheproof/tree/main/testvectors_v1
"""

import json
import sys


def motoko_text(value):
    """Returns `value` as a Motoko text literal."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    """Prints the Motoko module for the JSON file in sys.argv[1]."""
    path = sys.argv[1]
    data = json.load(open(path))
    assert data["schema"] == "ecdsa_verify_schema_v1.json", data["schema"]
    name = path.rsplit("/", 1)[-1]
    rows = []
    for group in data["testGroups"]:
        assert group["sha"] == "SHA-256", group["sha"]
        key = group["publicKey"]["uncompressed"]
        for test in group["tests"]:
            flags = ", ".join(motoko_text(f) for f in test["flags"])
            rows.append(
                "    {\n"
                f"      tcId = {test['tcId']};\n"
                f"      comment = {motoko_text(test['comment'])};\n"
                f"      key = {motoko_text(key)};\n"
                f"      msg = {motoko_text(test['msg'])};\n"
                f"      sig = {motoko_text(test['sig'])};\n"
                f"      result = {motoko_text(test['result'])};\n"
                f"      flags = [{flags}];\n"
                "    },\n"
            )
    assert len(rows) == data["numberOfTests"], (len(rows), data["numberOfTests"])
    print(f"""// Wycheproof {data['algorithm']} test vectors for {data['testGroups'][0]['publicKey']['curve']}
// with {data['testGroups'][0]['sha']}, from {name} in
// https://github.com/C2SP/wycheproof/tree/main/testvectors_v1 ({len(rows)} tests).
// Generated by scripts/wycheproof_ecdsa_to_motoko.py. Do not edit.

module {{
  public type WycheproofEcdsaTestCase = {{
    tcId : Nat;
    comment : Text;
    key : Text;
    msg : Text;
    sig : Text;
    result : Text;
    flags : [Text];
  }};

  public let testVectors : [WycheproofEcdsaTestCase] = [
{"".join(rows)}  ];
}};""")


if __name__ == "__main__":
    main()

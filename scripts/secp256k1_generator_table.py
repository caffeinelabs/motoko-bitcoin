#!/usr/bin/env python3
"""Generates src/ec/Secp256k1Generator.mo: the odd multiples of the
secp256k1 generator G, of H = 2^64 * G, and of their images under
phi(x, y) = (beta * x, y), in affine coordinates, for the wNAF window width
given on the command line.

Usage: python3 scripts/secp256k1_generator_table.py 7 > src/ec/Secp256k1Generator.mo
"""

import sys

P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
BETA = 0x7AE96A2B657C07106E64479EAC3434E99CF0497512F58995C1396C28719501EE
LAMBDA = 0x5363AD4CC05C30E0A5261C028812645A122E22EA20816678DF02967C1B23BD72
# The GLV half-scalars are split once more at this bit position.
SHIFT = 64


def add(p1, p2):
    """Adds two affine points (not the point at infinity) on secp256k1."""
    (x1, y1), (x2, y2) = p1, p2
    if p1 == p2:
        m = 3 * x1 * x1 * pow(2 * y1, -1, P) % P
    else:
        m = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (m * m - x1 - x2) % P
    return (x3, (m * (x1 - x3) - y1) % P)


def mul(k, point):
    """Multiplies an affine point by k > 0 with double-and-add."""
    acc = None
    for bit in bin(k)[2:]:
        acc = add(acc, acc) if acc else None
        if bit == "1":
            acc = add(acc, point) if acc else point
    return acc


def main():
    """Prints the generated Motoko module for the width in sys.argv[1]."""
    assert P == 2**256 - 2**32 - 977
    width = int(sys.argv[1])
    g = (GX, GY)

    def odd_multiples(base):
        """Returns base, 3 * base, ..., (2^(width - 1) - 1) * base, checked."""
        two = add(base, base)
        out = [base]
        for _ in range(2 ** (width - 2) - 1):
            out.append(add(out[-1], two))
        for i, point in enumerate(out):
            x, y = point
            assert (y * y - x * x * x - 7) % P == 0
            assert point == mul(2 * i + 1, base)
        return out

    def phi_of(points):
        """Applies the endomorphism phi(x, y) = (beta * x, y) to each point."""
        return [(BETA * x % P, y) for (x, y) in points]

    multiples = odd_multiples(g)
    phi = phi_of(multiples)
    assert phi[0] == mul(LAMBDA, g)
    h = mul(2**SHIFT, g)
    shifted = odd_multiples(h)
    phi_shifted = phi_of(shifted)
    assert phi_shifted[0] == mul(LAMBDA * 2**SHIFT, g)

    def table(points):
        """Formats points as a Motoko array literal of (x, y, 1) triples."""
        rows = "".join(f"    (0x{x:064x}, 0x{y:064x}, 1),\n" for x, y in points)
        return "[\n" + rows + "  ]"

    top = 2 ** (width - 1) - 1
    print(f"""/// Precomputed odd multiples of the secp256k1 generator `G`, of
/// `H = 2^{SHIFT} * G`, and of their endomorphism images `phi(G)` and
/// `phi(H)`, used by `Jacobi.mul`, `Jacobi.mulBase` and `Jacobi.mulAdd`
/// whenever a point is the generator.
///
/// Internal to the package: not a stable API. The window, the shift and the
/// table layout may change in any release.
///
/// Generated by `scripts/secp256k1_generator_table.py {width}`. Do not edit.
///
/// ```motoko name=import
/// import Secp256k1Generator "mo:bitcoin/ec/Secp256k1Generator";
/// ```

module {{
  /// The wNAF window width the tables are built for.
  public let window : Nat = {width};

  /// `G, 3G, ..., {top}G` in affine coordinates, as Jacobian triples `(x, y, 1)`.
  public let multiples : [(Nat, Nat, Nat)] = {table(multiples)};

  /// The images `phi(kG) = (beta * x, y)` of `multiples`, in the same order.
  public let phiMultiples : [(Nat, Nat, Nat)] = {table(phi)};

  /// The bit position at which the GLV half-scalars are split once more:
  /// `k = kLow + 2^shift * kHigh`.
  public let shift : Nat = {SHIFT};

  /// `H, 3H, ..., {top}H` for `H = 2^shift * G`, in affine coordinates.
  public let shiftedMultiples : [(Nat, Nat, Nat)] = {table(shifted)};

  /// The images `phi(kH)` of `shiftedMultiples`, in the same order.
  public let phiShiftedMultiples : [(Nat, Nat, Nat)] = {table(phi_shifted)};
}};""")


if __name__ == "__main__":
    main()
